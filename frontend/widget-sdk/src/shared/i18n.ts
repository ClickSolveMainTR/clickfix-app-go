/** RTL languages the widget lays out right-to-left. */
export const RTL = ["ar", "he", "fa", "ur"];

/** Picks tr/en from a browser language list. */
export function detectLocale(languages: readonly string[]): "tr" | "en" {
  for (const l of languages) {
    const code = l.toLowerCase().slice(0, 2);
    if (code === "tr" || code === "en") return code;
  }
  return "en";
}

export function format(s: string, vars: Record<string, string>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => vars[k] ?? m);
}
