// Generates the API reference pages (content/docs/<locale>/api-reference) from
// the docs copies of the public spec: one page per operation, grouped in a
// folder per tag, in Turkish and English. Slugs come from the English spec
// (tag name and summary), so both languages share URLs and a new tag or
// operation needs no mapping here.
import { createOpenAPI } from "fumadocs-openapi/server";
import { generateFiles } from "fumadocs-openapi";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { parse } from "yaml";

const SPECS = {
  en: "./content/api/public-api.yaml",
  tr: "./content/api/public-api.tr.yaml",
};
const METHODS = ["get", "put", "post", "delete", "patch", "head", "options"];

function slugify(text) {
  return text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// Tag order, slugs and operation slugs from the English spec.
const en = parse(await readFile(SPECS.en, "utf8"));
const tags = (en.tags ?? []).map((tag) => ({
  name: tag.name,
  slug: slugify(tag.name),
}));
const tagSlug = Object.fromEntries(tags.map((t) => [t.name, t.slug]));
const entries = {}; // "method path" | "webhook name" -> { tag, slug }
const used = new Set();
function register(key, tagName, summary) {
  const tag = tagSlug[tagName];
  if (!tag)
    throw new Error(
      `generate-api-docs: tag ${tagName} is not declared in the spec`,
    );
  let slug = slugify(summary);
  if (used.has(`${tag}/${slug}`))
    throw new Error(`generate-api-docs: duplicate page ${tag}/${slug}`);
  used.add(`${tag}/${slug}`);
  entries[key] = { tag, slug };
}
for (const [path, item] of Object.entries(en.paths ?? {})) {
  for (const method of METHODS) {
    const op = item[method];
    if (op) register(`${method} ${path}`, op.tags[0], op.summary);
  }
}
for (const [name, item] of Object.entries(en.webhooks ?? {})) {
  for (const method of METHODS) {
    const op = item[method];
    if (op) register(`webhook ${name}`, op.tags[0], op.summary);
  }
}
const keyOf = (entry) =>
  entry.type === "webhook"
    ? `webhook ${entry.item.name}`
    : `${entry.item.method} ${entry.item.path}`;

const INDEX = {
  en: {
    title: "API reference",
    description:
      "Every public endpoint with request and response schemas, examples and ready-made requests for curl, Node.js, Go and PHP.",
    intro:
      "Generated from the published API contract. Rules shared by every endpoint (keys, envelope, errors, pagination, idempotency, rate limits): [API](/docs/api?lang=en).",
  },
  tr: {
    title: "API başvurusu",
    description:
      "Her herkese açık uç nokta: istek ve yanıt şemaları, örnekler, curl, Node.js, Go ve PHP için hazır istekler.",
    intro:
      "Yayınlanan API sözleşmesinden üretilir. Her uç noktanın ortak kuralları (anahtar, zarf, hatalar, sayfalama, idempotency, hız sınırları): [API](/docs/api).",
  },
};

for (const [locale, input] of Object.entries(SPECS)) {
  const output = `./content/docs/${locale}/api-reference`;
  const openapi = createOpenAPI({ input: [input] });
  const localized = parse(await readFile(input, "utf8"));
  await rm(output, { recursive: true, force: true });
  await generateFiles({
    input: openapi,
    output,
    per: "operation",
    groupBy: (entry) => entries[keyOf(entry)].tag,
    name: (entry) => entries[keyOf(entry)].slug,
    includeDescription: true,
    addGeneratedComment:
      "Generated by frontend/scripts/generate-api-docs.mjs (pnpm docs:generate). Do not edit.",
  });
  // Folder titles in the page's language and the spec's order.
  const titles = Object.fromEntries(
    (localized.tags ?? []).map((t, i) => [tags[i].slug, t.name]),
  );
  const pages = [];
  for (const tag of tags) {
    const ops = Object.values(entries)
      .filter((e) => e.tag === tag.slug)
      .map((e) => e.slug);
    await mkdir(`${output}/${tag.slug}`, { recursive: true });
    await writeFile(
      `${output}/${tag.slug}/meta.json`,
      JSON.stringify({ title: titles[tag.slug], pages: ops }, null, 2) + "\n",
    );
    pages.push(tag.slug);
  }
  const copy = INDEX[locale];
  const q = locale === "en" ? "?lang=en" : "";
  const list = (localized.tags ?? [])
    .map(
      (t, i) =>
        `- [${t.name}](/docs/api-reference/${tags[i].slug}/${entries[Object.keys(entries).find((k) => entries[k].tag === tags[i].slug)].slug}${q}): ${t.description ?? ""}`,
    )
    .join("\n");
  await writeFile(
    `${output}/index.mdx`,
    `---\ntitle: ${copy.title}\ndescription: "${copy.description}"\n---\n\n${copy.intro}\n\n${list}\n`,
  );
  await writeFile(
    `${output}/meta.json`,
    JSON.stringify({ title: copy.title, pages: ["index", ...pages] }, null, 2) +
      "\n",
  );
  console.log(
    `api-reference (${locale}): ${Object.keys(entries).length} pages in ${pages.length} groups`,
  );
}
