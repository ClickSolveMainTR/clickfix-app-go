/** Shared native menu icon policy, with explicit overrides for domain-specific choices. */
export function menuSymbol(item: MenuOption): SFSymbol {
  return item.systemImage ?? (item.destructive ? 'trash' : (SYMBOLS[item.value.split(':')[0]!] ?? 'circle'));
}
